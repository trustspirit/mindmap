const assert = require('node:assert/strict');
const { createLibrary, saveMap, addWorkspace, selectWorkspace, makeMap, mergeLibraries, readLibrary } = require('../lib/library.ts');
const { validateCredentials, authErrorMessage } = require('../lib/auth.ts');
const legacy = { mapId: 'existing-map', title: '보존할 맵', nodes: [{id:'root',text:'기존 내용',color:'green',x:40,y:60}] };
let lib = createLibrary([],legacy);
assert.equal(lib.maps[0].id,legacy.mapId);
assert.deepEqual(lib.maps[0].nodes, legacy.nodes);
const originalId=lib.activeWorkspaceId;
lib=addWorkspace(lib,'프로젝트 A');
const secondId=lib.activeWorkspaceId;
assert.equal(lib.workspaces.length,2);
assert.equal(lib.maps.filter(m=>m.workspaceId===secondId).length,1);
assert.equal(lib.maps.find(m=>m.id===legacy.mapId).title,'보존할 맵');
const added=makeMap(secondId); added.title='두 번째 맵';
lib=saveMap(lib,added);
assert.equal(lib.maps.filter(m=>m.workspaceId===secondId).length,2);
lib=selectWorkspace(lib,originalId);
assert.equal(lib.activeMapId,legacy.mapId);
assert.throws(()=>addWorkspace(lib,' 프로젝트 A '));
assert.throws(()=>addWorkspace(lib,'  '));
assert.throws(()=>saveMap(lib,{...added,workspaceId:'unknown'}));
assert.deepEqual(readLibrary(JSON.stringify(lib)),lib);
const localMap={...added,updatedAt:'2026-11-07T10:00:00.000Z',title:'최신 로컬'};
const olderMap={...added,updatedAt:'2026-11-07T09:00:00.000Z',title:'이전 서버'};
const merged=mergeLibraries(saveMap(lib,localMap),{workspaces:[],maps:[olderMap]});
assert.equal(merged.maps.find(m=>m.id===added.id).title,'최신 로컬');
assert.equal(validateCredentials('login','name@example.com','validpass',''),'');
assert.notEqual(validateCredentials('signup','name@example.com','short','short'),'');
assert.notEqual(validateCredentials('signup','name@example.com','validpass','different'),'');
assert.notEqual(validateCredentials('signup','invalid','validpass','validpass'),'');
assert.equal(validateCredentials('signup','name@example.com','validpass','validpass'),'');
assert.match(authErrorMessage('invalid_credentials'),/아이디 또는 비밀번호/);
console.log('PASS: legacy migration, workspace isolation, multiple maps, switching, validation, persistence, sync conflict merge, signup validation');
